/* Build-time generator for the Command Brief maps (NO runtime dependency,
 * NO external tiles). Produces pre-projected SVG path strings.
 *
 * Inputs: Natural Earth via world-atlas@2.0.2 (public domain).
 * Run (from a scratch dir that has the packages installed):
 *   npm i d3-geo@3.1.1 topojson-client@3.1.0 topojson-simplify@3.0.3 \
 *         world-atlas@2.0.2 i18n-iso-countries@7.11.3
 *   NODE_PATH=./node_modules node <repo>/web/scripts/build-geo.cjs <repo>/web/src/lib/geo
 */
const fs = require("fs");
const path = require("path");
const d3 = require("d3-geo");
const topo = require("topojson-client");
const simp = require("topojson-simplify");
const iso = require("i18n-iso-countries");

const outDir = process.argv[2];
const r1 = (s) => s.replace(/(\d+\.\d)\d+/g, "$1");

function alpha3(f) {
  if (f.properties && f.properties.name === "Kosovo") return "xkx";
  if (f.properties && f.properties.name === "N. Cyprus") return "cyn";
  if (f.properties && f.properties.name === "Somaliland") return "sol";
  const a = iso.numericToAlpha3(String(f.id).padStart(3, "0"));
  return a ? a.toLowerCase() : null;
}

function build(file, opts) {
  let t = JSON.parse(fs.readFileSync(require.resolve("world-atlas/" + file)));
  if (opts.simplify) {
    t = simp.presimplify(t);
    t = simp.simplify(t, simp.quantile(t, opts.simplify));
  }
  const fc = topo.feature(t, t.objects.countries);
  const feats = fc.features.filter((f) => !opts.drop || !opts.drop.includes(alpha3(f)));
  const proj = opts.projection();
  if (opts.extentBox) {
    const [w, s, e, n] = opts.extentBox;
    const box = { type: "Feature", geometry: { type: "Polygon", coordinates: [[[w, s], [w, n], [e, n], [e, s], [w, s]]] } };
    proj.fitExtent([[0, 0], [opts.width, opts.height]], box);
    proj.clipExtent([[0, 0], [opts.width, opts.height]]);
  } else {
    proj.fitExtent([[4, 4], [opts.width - 4, opts.height - 4]], { type: "FeatureCollection", features: feats });
  }
  const gp = d3.geoPath(proj);
  const out = {};
  for (const f of feats) {
    const id = alpha3(f);
    if (!id) continue;
    const d = gp(f);
    if (!d) continue;
    const area = gp.area(f);
    if (area < (opts.minArea || 0)) continue;
    let c = (opts.labels && opts.labels[id]) ? proj(opts.labels[id]) : gp.centroid(f);
    if (!c || isNaN(c[0])) continue;
    out[id] = { d: r1(d), c: [Math.round(c[0] * 10) / 10, Math.round(c[1] * 10) / 10], name: f.properties.name };
  }
  return out;
}

const cee = build("countries-50m.json", {
  width: 600, height: 470, simplify: 0.25, minArea: 1,
  extentBox: [9.0, 39.0, 41.0, 60.0],
  projection: () => d3.geoConicConformal().parallels([42, 54]).rotate([-21, 0]),
  labels: { rus: [37.5, 54.0], ukr: [31.5, 49.0], tur: [31.5, 40.3], nor: [10, 57], swe: [15, 57], deu: [11.5, 51.2], ita: [12.5, 42.8], hrv: [15.6, 45.5], grc: [22, 39.9], kaz: [40.5, 49] },
});
const world = build("countries-110m.json", {
  width: 800, height: 410, simplify: 0.4, minArea: 0,
  projection: () => d3.geoNaturalEarth1(),
  drop: ["ata"],
  labels: { usa: [-98, 39], rus: [90, 61], can: [-100, 58], fra: [2.5, 46.5], nor: [9, 61], chl: [-71, -33] },
});

const header = "/* GENERATED by web/scripts/build-geo.cjs from Natural Earth (world-atlas 2.0.2,\n * public domain). Pre-projected SVG paths — no runtime map library, no tiles. */\n";
fs.writeFileSync(path.join(outDir, "cee.ts"),
  header + "export const CEE_VIEWBOX = \"0 0 600 470\";\n" +
  "export const CEE: Record<string, { d: string; c: [number, number]; name: string }> = " + JSON.stringify(cee) + ";\n");
fs.writeFileSync(path.join(outDir, "world.ts"),
  header + "export const WORLD_VIEWBOX = \"0 0 800 410\";\n" +
  "export const WORLD: Record<string, { d: string; c: [number, number]; name: string }> = " + JSON.stringify(world) + ";\n");
console.log("cee", Object.keys(cee).length, "world", Object.keys(world).length);
