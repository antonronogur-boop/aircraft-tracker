import { loadReports } from "@/lib/reports";
import { PageHeader } from "@/components/ui";
import { WeeklyReportView } from "@/components/WeeklyReportView";
import { BriefEmbed } from "@/components/BriefEmbed";
import { PrintButton } from "@/components/PrintButton";
import Link from "next/link";

export const dynamic = "force-dynamic";

export type { ReportRow } from "@/lib/reports";

export default async function WeeklyPage() {
  const reports = await loadReports(30);
  const latest = reports[0];

  return (
    <div>
      {/* Nyomtataskor a jelentes ELSO 4 oldala a Command Brief: a fejlec
          ilyenkor nem kerul a PDF-be (a briefnek sajat fejlece van). */}
      <div className={`flex flex-wrap items-start justify-between gap-3 ${latest?.payload?.command_brief ? "cb-print-hide" : ""}`}>
        <PageHeader
          title="Weekly report"
          description={latest
            ? `Latest analyst report — generated ${latest.generated_at?.slice(0, 16).replace("T", " ")} UTC. Archived weekly.`
            : "No archived report yet."}
        />
        {latest && (
          <div className="flex items-center gap-2 print:hidden">
            {latest.payload?.command_brief && (
              <Link href="/weekly/command-brief"
                    className="rounded border border-amber-600/60 bg-amber-500/10 px-3 py-1.5 text-xs text-amber-200 hover:border-amber-400">
                Command brief (4 pages) →
              </Link>
            )}
            {/* A 4 slide-os briefing nezet — ebbol lehet eloadni. */}
            <Link href={`/weekly/${latest.week_label}/brief`}
                  className="rounded border border-cyan-700/60 bg-cyan-500/10 px-3 py-1.5 text-xs text-cyan-200 hover:border-cyan-500">
              4-slide briefing →
            </Link>
            <PrintButton />
          </div>
        )}
      </div>

      {!latest ? (
        <p className="text-sm text-slate-600">
          The first report is generated by the Wednesday pipeline run — or trigger it manually:
          GitHub → Actions → weekly-digest → Run workflow (or run
          scripts/generate_weekly_report.py locally).
        </p>
      ) : (
        <>
        <BriefEmbed payload={latest.payload} />
        <WeeklyReportView
          payload={latest.payload}
          weekLabel={latest.week_label}
          periodStart={latest.period_start}
          periodEnd={latest.period_end}
        />
        </>
      )}

      {reports.length > 1 && (
        <section className="mt-10 print:hidden">
          <h2 className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-500">
            Report archive
          </h2>
          <div className="flex flex-wrap gap-2">
            {reports.slice(1).map((r) => (
              <Link key={r.report_id} href={`/weekly/${r.week_label}`}
                    className="rounded border border-slate-800 bg-slate-900/40 px-3 py-1.5 text-xs text-slate-400 hover:border-slate-600 hover:text-slate-200">
                {r.week_label} <span className="text-slate-600">({r.period_start} → {r.period_end})</span>
              </Link>
            ))}
          </div>
        </section>
      )}
    </div>
  );
}
